package cloud

import (
	"fmt"

	cf "github.com/pulumi/pulumi-cloudflare/sdk/v6/go/cloudflare"
	"github.com/pulumi/pulumi/sdk/v3/go/pulumi"

	"github.com/madhank93/homelab/config"
	"github.com/madhank93/homelab/core/internal/cfg"
)

// PublicService describes a service exposed to the public internet via the Hetzner VPS.
// SkipAuth bypasses Authentik ForwardAuth, for services that run their own login.
type PublicService struct {
	Name     string
	SkipAuth bool
}

// publicServices lists services exposed to the public internet via the Hetzner VPS.
// Each entry creates an A record pointing to the VPS IP and a Traefik router in
// public-services.yml (generated by generateTraefikPublicServices in hetzner.go).
// To make a service LAN-only: remove it from this list — DNS falls back to the wildcard.
var publicServices = []PublicService{
	// Grafana runs its own Authentik OIDC login, so forwardauth would only add a second prompt.
	{Name: "grafana", SkipAuth: true},
}

// ManageCloudflare provisions Cloudflare DNS records for the homelab domain.
//
// A wildcard record points every subdomain at the LAN gateway, so a name is
// private unless it has its own record. The Proxmox host gets its LAN IP; the
// always-public Bifrost names (auth, netbird, proxy, *.proxy, uptime) and each
// [publicServices] entry point at the VPS. Records are DNS-only, not proxied.
func ManageCloudflare(ctx *pulumi.Context) error {
	hetznerIP := config.C.Hetzner.VPSIP

	cfToken := cfg.K.String("CLOUDFLARE_API_TOKEN")
	if cfToken == "" {
		return fmt.Errorf("CLOUDFLARE_API_TOKEN not in environment")
	}

	provider, err := cf.NewProvider(ctx, "cloudflare", &cf.ProviderArgs{
		ApiToken: pulumi.String(cfToken),
	})
	if err != nil {
		return err
	}

	zoneID := config.C.Cloudflare.ZoneID

	// The v6 SDK registers DnsRecord with an alias to cloudflare:index/record:Record,
	// so records created by the v5 provider keep their URNs.
	newRecord := func(name, logicalName, ip, comment string) error {
		_, err := cf.NewDnsRecord(ctx, logicalName, &cf.DnsRecordArgs{
			ZoneId:  pulumi.String(zoneID),
			Name:    pulumi.String(name),
			Type:    pulumi.String("A"),
			Content: pulumi.String(ip),
			Ttl:     pulumi.Float64(1),
			Proxied: pulumi.Bool(false),
			Comment: pulumi.StringPtr(comment),
		}, pulumi.Provider(provider))
		return err
	}

	if err := newRecord("*", "wildcard-madhan-app", config.C.Cluster.GatewayIP, "Homelab wildcard - LAN gateway"); err != nil {
		return err
	}

	// Proxmox host, LAN only; its Let's Encrypt cert is ordered by the talos stack.
	if err := newRecord(config.C.Host(config.C.Proxmox.Host), "proxmox-host", config.C.Proxmox.IP, "Proxmox VE - LAN only"); err != nil {
		return err
	}

	// Authentik, NetBird, the NetBird expose base and the Gatus status page.
	for _, svc := range []string{"auth", "netbird", "proxy", "uptime"} {
		if err := newRecord(config.C.Host(svc), "always-public-"+svc, hetznerIP, "Bifrost VPS - always public"); err != nil {
			return err
		}
	}

	// Services published with NetBird expose.
	if err := newRecord(config.C.Host("*.proxy"), "wildcard-proxy-madhan-app", hetznerIP, "NetBird expose wildcard"); err != nil {
		return err
	}

	for _, svc := range publicServices {
		comment := "Public via Bifrost+Authentik SSO"
		if svc.SkipAuth {
			comment = "Public via Bifrost (self-managed auth)"
		}
		if err := newRecord(config.C.Host(svc.Name), "public-svc-"+svc.Name, hetznerIP, comment); err != nil {
			return err
		}
	}

	return nil
}
